#!/usr/bin/env python
"""
Generate results_ablation.tex from the ablation experiment output.

Reads results.json and stats_{psnr,ssim}.json produced by the ablation runner
and emits the LaTeX fragment the paper \\input{}s. Keeping this generated rather
than hand-written means the numbers in the paper cannot drift from the numbers
the experiment produced.

    python paper/make_results_table.py --results <dir> --out paper/results_ablation.tex
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

# Display name and one-line description for each run, in table order.
LABELS = [
    ("zero-filled", "Zero-filled (no network)", "--"),
    ("unet-mag", "U-Net, magnitude", "0.48"),
    ("unet-cplx", "U-Net, complex", "0.48"),
    ("unet-wide", "U-Net, complex, wide", "1.00"),
    ("unet-dc2", "U-Net + DC cascade ($T{=}2$)", "0.97"),
    ("swin-mag", "SwinUNet, magnitude", "0.21"),
    ("swin-wide", "SwinUNet, complex, wide", "0.47"),
    ("swin-dc2", "SwinUNet + DC cascade ($T{=}2$)", "0.43"),
]


def fmt_p(comp: dict | None) -> str:
    if comp is None:
        return "--"
    p = comp.get("p_adjusted", comp.get("p_value", 1.0))
    star = "$^{*}$" if comp.get("significant") else ""
    return (f"$<10^{{-4}}${star}" if p < 1e-4 else f"{p:.4f}{star}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", required=True, help="Directory holding results.json")
    ap.add_argument("--out", required=True, help="Output .tex fragment")
    args = ap.parse_args()

    root = Path(args.results)
    results = json.loads((root / "results.json").read_text())
    stats_psnr = json.loads((root / "stats_psnr.json").read_text())
    stats_ssim = json.loads((root / "stats_ssim.json").read_text())

    per_sample = {}
    ps_path = root / "per_sample.json"
    if ps_path.exists():
        per_sample = json.loads(ps_path.read_text())
    intervals = stats_psnr.get("intervals", {})
    comps_psnr = stats_psnr.get("comparisons", {})
    comps_ssim = stats_ssim.get("comparisons", {})
    reference = stats_psnr.get("reference", "unet-mag")

    lines: list[str] = []
    add = lines.append

    add("% Generated by paper/make_results_table.py -- do not edit by hand.")
    add("")
    add(
        "To separate the contribution of the data-consistency constraint from "
        "that of complex-valued input and of raw parameter count, I trained "
        "seven configurations on synthetic phantom data: 60 training volumes "
        "(240 slices) and 20 held-out validation volumes (80 slices), split at "
        "the volume level so no slice from a training volume appears in "
        "validation. All runs used $R = 4$ random Cartesian undersampling with "
        "an \\SI{8}{\\percent} fully sampled centre, $128\\times128$ crops, 30 "
        "epochs, identical optimiser and schedule settings, and three seeds; "
        "the median-SSIM seed is reported."
    )
    add("")
    add(
        "The \\emph{wide} rows are capacity-matched single-pass controls: they "
        "have slightly \\emph{more} parameters than the corresponding "
        "two-stage cascade, so any advantage the cascade shows cannot be "
        "attributed to capacity. This control is the point of the experiment. "
        "A cascade of $T$ stages has $T$ times the parameters of its backbone, "
        "and attributing its gain to physics without controlling for that "
        "would repeat, in subtler form, the kind of error this paper set out "
        "to correct."
    )
    add("")

    # ── Main results table ────────────────────────────────────────────────
    add("\\begin{table}[h]")
    add("\\centering")
    add("\\small")
    add("\\begin{tabular}{@{}lrrrr@{}}")
    add("\\toprule")
    add("Configuration & Params (M) & PSNR (dB) & SSIM & NMSE \\\\")
    add("\\midrule")

    for key, label, _ in LABELS:
        if key not in results:
            continue
        m = results[key]
        params = "--" if key == "zero-filled" else f"{m.get('params_m', 0):.2f}"
        add(
            f"{label} & {params} & {m['psnr_db']:.2f} & "
            f"{m['ssim']:.4f} & {m['nmse']:.5f} \\\\"
        )
        if key == "zero-filled":
            add("\\midrule")

    add("\\bottomrule")
    add("\\end{tabular}")
    add(
        "\\caption{Controlled ablation on synthetic phantoms, $R = 4$, "
        "80 held-out validation slices. Metrics are per-image means against "
        "each target's own dynamic range.}"
    )
    add("\\label{tab:ablation}")
    add("\\end{table}")
    add("")

    # ── Statistical table ─────────────────────────────────────────────────
    add(
        f"Table~\\ref{{tab:ablation-stats}} reports paired comparisons against "
        f"the \\mbox{{{reference}}} baseline. Because every model is evaluated "
        "on the same slices in the same order, the test can be paired, which "
        "cancels the shared per-slice difficulty and is what makes differences "
        "of this size resolvable at $n = 80$."
    )
    add("")
    add("\\begin{table}[h]")
    add("\\centering")
    add("\\small")
    add("\\begin{tabular}{@{}lccrr@{}}")
    add("\\toprule")
    add(
        "Configuration & PSNR 95\\% CI (dB) & $\\Delta$PSNR & "
        "$p$ (PSNR) & $p$ (SSIM) \\\\"
    )
    add("\\midrule")

    for key, label, _ in LABELS:
        if key not in intervals:
            continue
        iv = intervals[key]
        ci = f"[{iv['ci_low']:.2f}, {iv['ci_high']:.2f}]"
        if key == reference:
            add(f"{label} (ref.) & {ci} & -- & -- & -- \\\\")
        else:
            cp = comps_psnr.get(key)
            cs = comps_ssim.get(key)
            delta = f"{cp['mean_diff']:+.2f}" if cp else "--"
            add(f"{label} & {ci} & {delta} & {fmt_p(cp)} & {fmt_p(cs)} \\\\")

    add("\\bottomrule")
    add("\\end{tabular}")
    add(
        "\\caption{Paired permutation tests (\\num{10000} sign flips) against "
        "the magnitude-only U-Net, with Holm--Bonferroni correction across the "
        "family. $^{*}$ denotes significance at $\\alpha = 0.05$ after "
        "correction. Confidence intervals are percentile bootstrap "
        "(\\num{10000} resamples) on the per-slice mean.}"
    )
    add("\\label{tab:ablation-stats}")
    add("\\end{table}")
    add("")

    # ── Capacity-matched contrast: the paper's central claim ──────────────
    # Deltas against the magnitude baseline do not test the claim. The claim is
    # that data consistency beats an equal-parameter single-pass network, so
    # that pair has to be tested directly.
    pairs = [
        ("unet-dc2", "unet-wide", "U-Net"),
        ("swin-dc2", "swin-wide", "SwinUNet"),
    ]
    available = [(d, w, fam) for d, w, fam in pairs if d in per_sample and w in per_sample]

    if available:
        from training.stats import paired_permutation_test

        add(
            "The comparison that actually tests the hypothesis is each cascade "
            "against its own capacity-matched control, reported in "
            "Table~\\ref{tab:ablation-dc}. Deltas against the magnitude-only "
            "baseline conflate three effects at once; this pair isolates the "
            "data-consistency constraint with parameter count held fixed (in "
            "fact slightly favouring the control)."
        )
        add("")
        add("\\begin{table}[h]")
        add("\\centering")
        add("\\small")
        add("\\begin{tabular}{@{}lccccc@{}}")
        add("\\toprule")
        add(
            "Backbone & Cascade & Control & $\\Delta$PSNR (dB) & 95\\% CI & $p$ \\\\"
        )
        add("\\midrule")

        for dc_key, ctrl_key, family in available:
            # PSNR throughout this table; the aggregate means it is compared
            # against are `psnr_db`, so mixing metrics here would be incoherent.
            test = paired_permutation_test(
                per_sample[dc_key]["psnr"], per_sample[ctrl_key]["psnr"]
            )
            dc_mean = results[dc_key]["psnr_db"]
            ctrl_mean = results[ctrl_key]["psnr_db"]
            p = test["p_value"]
            p_str = "$<10^{-4}$" if p < 1e-4 else f"{p:.4f}"
            star = "$^{*}$" if p < 0.05 else ""
            ci = f"[{test['diff_ci_low']:+.2f}, {test['diff_ci_high']:+.2f}]"
            add(
                f"{family} & {dc_mean:.2f} & {ctrl_mean:.2f} & "
                f"{test['mean_diff']:+.2f} & {ci} & {p_str}{star} \\\\"
            )

        add("\\bottomrule")
        add("\\end{tabular}")
        add(
            "\\caption{Data consistency against a capacity-matched single-pass "
            "control, per backbone. Both members of each pair are complex-valued "
            "and differ only in whether the measured $k$-space is projected back "
            "after each refinement. Paired permutation test on per-slice "
            "differences; $^{*}$ significant at $\\alpha = 0.05$.}"
        )
        add("\\label{tab:ablation-dc}")
        add("\\end{table}")
        add("")

    # ── Seed stability ────────────────────────────────────────────────────
    seeded = [(k, results[k]) for k, _, _ in LABELS if results.get(k, {}).get("seed_psnr")]
    if seeded:
        add(
            "Run-to-run variation across the three seeds is reported in "
            "Table~\\ref{tab:ablation-seeds}. This matters for interpretation: "
            "a difference between configurations is only meaningful if it "
            "exceeds the spread produced by re-running the same configuration."
        )
        add("")
        add("\\begin{table}[h]")
        add("\\centering")
        add("\\small")
        add("\\begin{tabular}{@{}lcc@{}}")
        add("\\toprule")
        add("Configuration & PSNR across seeds (dB) & SSIM across seeds \\\\")
        add("\\midrule")
        for key, m in seeded:
            label = next(lb for k, lb, _ in LABELS if k == key)
            psnrs = " / ".join(f"{v:.2f}" for v in m["seed_psnr"])
            ssims = " / ".join(f"{v:.4f}" for v in m["seed_ssim"])
            add(f"{label} & {psnrs} & {ssims} \\\\")
        add("\\bottomrule")
        add("\\end{tabular}")
        add("\\caption{Per-seed results (seeds 0, 1, 2).}")
        add("\\label{tab:ablation-seeds}")
        add("\\end{table}")
        add("")

    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.out} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
